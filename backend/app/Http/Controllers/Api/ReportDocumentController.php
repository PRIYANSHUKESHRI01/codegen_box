<?php

namespace App\Http\Controllers\Api;

use App\Http\Controllers\Controller;
use App\Models\ActivityLog;
use App\Models\GeneratedReport;
use App\Models\User;
use App\Services\Reports\PdfRenderer;
use App\Services\Reports\ReportArchive;
use App\Services\Reports\StudentReportComposer;
use App\Support\ReportAccess;
use App\Support\ReportFormat;
use Illuminate\Http\JsonResponse;
use Illuminate\Http\Request;
use Illuminate\Support\Facades\Storage;
use Illuminate\Support\Str;
use Symfony\Component\HttpFoundation\Response;
use ZipArchive;

/**
 * Student report PDFs, for every role that may read them (see App\Support\ReportAccess for who that is). One controller serves
 * the TPO, the section coordinator, platform staff and the student themselves, mounted under each role's own prefix, so the
 * PDF and the rules around it are identical everywhere.
 *
 * "Generate" renders the report now, stores the file in the archive and returns its record; "download" streams the STORED
 * file (the very bytes that were generated). A report is therefore never regenerated by a download — it is a record of that day.
 */
class ReportDocumentController extends Controller
{
    /** The most reports one bundle may zip — a bundle is built in memory-light chunks but still has to finish inside a request. */
    private const BUNDLE_LIMIT = 60;

    public function __construct(
        private readonly StudentReportComposer $composer,
        private readonly PdfRenderer $pdf,
        private readonly ReportArchive $archive,
    ) {}

    /** POST …/students/{student}/reports — render, store, return. */
    public function store(Request $request, User $student): JsonResponse
    {
        $actor = $request->user();
        abort_unless(ReportAccess::student($actor, $student), 404);

        return response()->json(['report' => $this->generate($actor, $student)->present()], 201);
    }

    /** POST /me/report — a student's own report (written for them: no internal follow-up notes). */
    public function storeMine(Request $request): JsonResponse
    {
        $actor = $request->user();
        abort_unless(ReportAccess::student($actor, $actor), 404);

        return response()->json(['report' => $this->generate($actor, $actor)->present()], 201);
    }

    /** GET …/students/{student}/reports — every report ever generated about this student that the caller may see. */
    public function indexForStudent(Request $request, User $student): JsonResponse
    {
        $actor = $request->user();
        abort_unless(ReportAccess::student($actor, $student), 404);

        $reports = GeneratedReport::query()
            ->where('subject_user_id', $student->id)
            ->where('kind', in_array($request->query('kind'), GeneratedReport::KINDS, true) ? $request->query('kind') : GeneratedReport::KIND_STUDENT)
            ->with(['generator:id,name', 'interview:id,slug,title'])
            ->latest('id')
            ->limit(50)
            ->get()
            ->filter(fn (GeneratedReport $r) => ReportAccess::report($actor, $r->setRelation('subject', $student)))
            ->values();

        return response()->json(['reports' => $reports->map->present()]);
    }

    public function indexMine(Request $request): JsonResponse
    {
        return $this->indexForStudent($request, $request->user());
    }

    /** GET /tpo/reports/archive — the college-wide archive (student, interview and section reports), filterable and paged. */
    public function archive(Request $request): JsonResponse
    {
        $actor = $request->user();
        abort_unless($actor->role === User::ROLE_ADMIN_TPO && $actor->college_id !== null, 404);

        $page = $this->archive->query($actor->college_id, $request)->paginate(min(50, max(5, (int) $request->query('per_page', 20))));

        $totals = GeneratedReport::query()->where('college_id', $actor->college_id)
            ->selectRaw('kind, count(*) as n, coalesce(sum(size_bytes), 0) as bytes')->groupBy('kind')->get()
            ->mapWithKeys(fn ($r) => [$r->kind => ['count' => (int) $r->n, 'bytes' => (int) $r->bytes]]);

        return response()->json([
            'reports' => $page->getCollection()->map->present()->values(),
            'meta' => ['page' => $page->currentPage(), 'last_page' => $page->lastPage(), 'total' => $page->total()],
            'totals' => $totals,
        ]);
    }

    /** GET …/reports/{report}/download — the stored file. */
    public function download(Request $request, GeneratedReport $report): Response
    {
        $report->loadMissing('subject');
        abort_unless(ReportAccess::report($request->user(), $report), 404);

        return $this->archive->download($report);
    }

    /** DELETE /tpo/reports/{report} — a TPO may clear an old report (and its file) from their college's archive. */
    public function destroy(Request $request, GeneratedReport $report): JsonResponse
    {
        $actor = $request->user();
        abort_unless($actor->role === User::ROLE_ADMIN_TPO && ReportAccess::report($actor, $report), 404);

        ActivityLog::record($actor, 'Deleted a stored report', 'GeneratedReport', $report->title, ['kind' => $report->kind]);
        $this->archive->forget($report);

        return response()->json(['message' => 'Report deleted.']);
    }

    /**
     * POST /tpo/reports/bundle {ids: [...]} — the chosen stored reports as one .zip (e.g. a whole section's reports to hand to
     * the faculty). Only reports of the caller's college are included; any other id is silently dropped, never revealed.
     */
    public function bundle(Request $request): Response
    {
        $actor = $request->user();
        abort_unless($actor->role === User::ROLE_ADMIN_TPO && $actor->college_id !== null, 404);

        $ids = $request->validate([
            'ids' => ['required', 'array', 'min:1', 'max:'.self::BUNDLE_LIMIT],
            'ids.*' => ['string', 'size:26'],
        ])['ids'];

        $reports = GeneratedReport::query()->where('college_id', $actor->college_id)->whereIn('public_id', $ids)->get();
        abort_if($reports->isEmpty(), 404);

        $tmp = tempnam(sys_get_temp_dir(), 'aptrun-reports-');
        $zip = new ZipArchive;
        abort_unless($zip->open($tmp, ZipArchive::OVERWRITE) === true, 500, 'Could not prepare the download.');

        $used = [];
        foreach ($reports as $report) {
            $disk = Storage::disk($report->disk);
            if (! $disk->exists($report->path)) {
                continue;
            }
            $name = $report->filename;
            $used[$name] = ($used[$name] ?? 0) + 1;
            if ($used[$name] > 1) {
                $name = preg_replace('/\.pdf$/i', '', $name).'-'.$used[$name].'.pdf';
            }
            $zip->addFromString($name, $disk->get($report->path));
        }
        $zip->close();

        $name = 'AptRun-reports-'.now()->format('Ymd-His').'.zip';

        return response()->download($tmp, $name, ['Content-Type' => 'application/zip', 'Cache-Control' => 'private, no-store'])->deleteFileAfterSend(true);
    }

    private function generate(User $actor, User $student): GeneratedReport
    {
        $audience = ReportAccess::audience($actor, $student);
        $data = $this->composer->compose($student, $audience);

        $id = (string) Str::ulid();
        $label = 'AR-'.strtoupper(substr($id, -10));
        $filename = 'AptRun-Student-Report-'.ReportFormat::slug($student->name).($student->roll_number ? '-'.ReportFormat::slug($student->roll_number) : '').'-'.now()->format('Ymd').'.pdf';

        $footer = "Report {$label}  |  ".($audience === GeneratedReport::AUDIENCE_STAFF ? 'Confidential: personal data of '.Str::limit($student->name, 28) : 'Your AptRun report');
        $rendered = $this->pdf->render('reports.student', ['data' => $data], $footer);

        $report = $this->archive->store($rendered['binary'], [
            'public_id' => $id,
            'kind' => GeneratedReport::KIND_STUDENT,
            'title' => $student->name.' — student report',
            'filename' => $filename,
            'college_id' => $student->college_id,
            'subject_user_id' => $student->id,
            'audience' => $audience,
            'pages' => $rendered['pages'],
            'params' => ['audience' => $audience, 'label' => $label],
            'summary' => StudentReportComposer::snapshot($data),
        ], $actor);

        // A staff member reading a student's data is worth a line in the audit trail; a student reading their own is not.
        if ($actor->id !== $student->id) {
            ActivityLog::record($actor, 'Generated a student report', 'User', $student->name, ['report' => $label, 'pages' => $rendered['pages']]);
        }

        return $report->load(['generator:id,name', 'subject:id,name,roll_number,section,branch']);
    }
}
