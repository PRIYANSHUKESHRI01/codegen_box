import os
import re
import math
from go_articles_p1 import ARTICLES_PART1
from go_articles_p2 import ARTICLES_PART2

ALL_ARTICLES = ARTICLES_PART1 + ARTICLES_PART2

def estimate_reading_time(text: str) -> int:
    words = len(re.findall(r'\b\w+\b', text))
    return max(1, round(words / 200))

def escape_mysql_string(val: str) -> str:
    # Escape backslashes, single quotes, double quotes
    val = val.replace('\\', '\\\\')
    val = val.replace("'", "\\'")
    val = val.replace('"', '\\"')
    return val

def generate_php_seeder(articles):
    lines = []
    lines.append("<?php")
    lines.append("")
    lines.append("namespace Database\\Seeders;")
    lines.append("")
    lines.append("use App\\Models\\Article;")
    lines.append("use App\\Models\\ArticleTopic;")
    lines.append("use App\\Models\\User;")
    lines.append("use Illuminate\\Database\\Seeder;")
    lines.append("")
    lines.append("/**")
    lines.append(" * Seeds the complete 10-article Go Programming curriculum.")
    lines.append(" * Each article covers production architecture, runtime internals, memory layout,")
    lines.append(" * concurrency safety, tooling, and idiomatic API design.")
    lines.append(" *")
    lines.append(" * Idempotent (updateOrCreate by slug).")
    lines.append(" */")
    lines.append("class GoArticlesSeeder extends Seeder")
    lines.append("{")
    lines.append("    public function run(): void")
    lines.append("    {")
    lines.append("        $go = ArticleTopic::where('slug', 'go-programming')->first();")
    lines.append("")
    lines.append("        if (! $go) {")
    lines.append('            $this->command?->error("Go Programming article topic not found. Run ArticleTopicSeeder first.");')
    lines.append("            return;")
    lines.append("        }")
    lines.append("")
    lines.append("        $author = User::where('email', 'priya@mellow.ai')->first()")
    lines.append("            ?? User::where('role', User::ROLE_SUPERADMIN)->first()")
    lines.append("            ?? User::first();")
    lines.append("")
    lines.append("        if (! $author) {")
    lines.append('            $this->command?->error("No valid author found to associate with articles.");')
    lines.append("            return;")
    lines.append("        }")
    lines.append("")
    lines.append("        $articles = [")

    for i, a in enumerate(articles, start=1):
        slug_func = re.sub(r'[^a-zA-Z0-9]', '', a['slug'].title())
        func_name = slug_func[0].lower() + slug_func[1:] + "Article"
        excerpt_clean = a['excerpt'].replace("'", "\\'")

        lines.append("            [")
        lines.append(f"                'slug' => '{a['slug']}',")
        lines.append(f"                'title' => '{a['title'].replace(chr(39), chr(92)+chr(39))}',")
        lines.append(f"                'excerpt' => '{excerpt_clean}',")
        lines.append(f"                'display_order' => {a['display_order']},")
        lines.append(f"                'content' => $this->{func_name}(),")
        lines.append("            ],")

    lines.append("        ];")
    lines.append("")
    lines.append("        foreach ($articles as $data) {")
    lines.append("            $content = $data['content'];")
    lines.append("            Article::updateOrCreate(")
    lines.append("                ['slug' => $data['slug']],")
    lines.append("                [")
    lines.append("                    'article_topic_id' => $go->id,")
    lines.append("                    'title' => $data['title'],")
    lines.append("                    'excerpt' => $data['excerpt'],")
    lines.append("                    'content' => $content,")
    lines.append("                    'icon' => null,")
    lines.append("                    'status' => Article::STATUS_PUBLISHED,")
    lines.append("                    'display_order' => $data['display_order'],")
    lines.append("                    'reading_time_minutes' => Article::estimateReadingTimeMinutes($content),")
    lines.append("                    'created_by' => $author->id,")
    lines.append("                    'published_at' => now(),")
    lines.append("                ]")
    lines.append("            );")
    lines.append("        }")
    lines.append("    }")

    # Now add each private article content method
    for i, a in enumerate(articles, start=1):
        slug_func = re.sub(r'[^a-zA-Z0-9]', '', a['slug'].title())
        func_name = slug_func[0].lower() + slug_func[1:] + "Article"
        lines.append("")
        lines.append(f"    private function {func_name}(): string")
        lines.append("    {")
        lines.append("        return <<<'MARKDOWN'")
        lines.append(a['content'])
        lines.append("MARKDOWN;")
        lines.append("    }")

    lines.append("}")
    lines.append("")
    return "\n".join(lines)


def generate_sql_file(articles):
    lines = []
    lines.append("-- ==============================================================================")
    lines.append("-- AptRun Go Programming Articles Update (10 Comprehensive Articles)")
    lines.append("-- Generated for AWS RDS / Production MySQL")
    lines.append("-- Target Topic: Go Programming (`go-programming`)")
    lines.append("-- Date: 2026-11-23")
    lines.append("-- Idempotent: Safe to run multiple times via ON DUPLICATE KEY UPDATE.")
    lines.append("-- ==============================================================================")
    lines.append("")
    lines.append("SET NAMES utf8mb4;")
    lines.append("SET FOREIGN_KEY_CHECKS = 0;")
    lines.append("")
    lines.append("-- 1. Ensure Topic exists")
    lines.append("INSERT INTO `article_topics` (`slug`, `name`, `description`, `icon`, `color`, `display_order`, `created_at`, `updated_at`)")
    lines.append("VALUES (")
    lines.append("    'go-programming',")
    lines.append("    'Go Programming',")
    lines.append("    'Practical, production-minded deep-dives into Go — starting with what makes its concurrency model genuinely different.',")
    lines.append("    'Cpu',")
    lines.append("    'sky',")
    lines.append("    2,")
    lines.append("    NOW(),")
    lines.append("    NOW()")
    lines.append(")")
    lines.append("ON DUPLICATE KEY UPDATE")
    lines.append("    `name` = VALUES(`name`),")
    lines.append("    `description` = VALUES(`description`),")
    lines.append("    `icon` = VALUES(`icon`),")
    lines.append("    `color` = VALUES(`color`),")
    lines.append("    `display_order` = VALUES(`display_order`),")
    lines.append("    `updated_at` = NOW();")
    lines.append("")
    lines.append("-- 2. Resolve topic and author IDs dynamically")
    lines.append("SET @go_topic_id = (SELECT `id` FROM `article_topics` WHERE `slug` = 'go-programming' LIMIT 1);")
    lines.append("SET @author_id = (")
    lines.append("    SELECT `id` FROM `users` WHERE `email` = 'priya@mellow.ai'")
    lines.append("    UNION")
    lines.append("    SELECT `id` FROM `users` WHERE `role` = 'superadmin'")
    lines.append("    UNION")
    lines.append("    SELECT `id` FROM `users` ORDER BY `id` ASC LIMIT 1")
    lines.append(");")
    lines.append("")

    for i, a in enumerate(articles, start=1):
        rt = estimate_reading_time(a['content'])
        title_esc = escape_mysql_string(a['title'])
        slug_esc = escape_mysql_string(a['slug'])
        excerpt_esc = escape_mysql_string(a['excerpt'])
        content_esc = escape_mysql_string(a['content'])

        lines.append(f"-- ------------------------------------------------------------------------------")
        lines.append(f"-- Article {i}: {a['title']}")
        lines.append(f"-- ------------------------------------------------------------------------------")
        lines.append("INSERT INTO `articles` (")
        lines.append("    `article_topic_id`,")
        lines.append("    `title`,")
        lines.append("    `slug`,")
        lines.append("    `excerpt`,")
        lines.append("    `content`,")
        lines.append("    `icon`,")
        lines.append("    `status`,")
        lines.append("    `display_order`,")
        lines.append("    `reading_time_minutes`,")
        lines.append("    `created_by`,")
        lines.append("    `published_at`,")
        lines.append("    `created_at`,")
        lines.append("    `updated_at`")
        lines.append(")")
        lines.append("VALUES (")
        lines.append("    @go_topic_id,")
        lines.append(f"    '{title_esc}',")
        lines.append(f"    '{slug_esc}',")
        lines.append(f"    '{excerpt_esc}',")
        lines.append(f"    '{content_esc}',")
        lines.append("    NULL,")
        lines.append("    'published',")
        lines.append(f"    {a['display_order']},")
        lines.append(f"    {rt},")
        lines.append("    @author_id,")
        lines.append("    NOW(),")
        lines.append("    NOW(),")
        lines.append("    NOW()")
        lines.append(")")
        lines.append("ON DUPLICATE KEY UPDATE")
        lines.append("    `article_topic_id` = VALUES(`article_topic_id`),")
        lines.append("    `title` = VALUES(`title`),")
        lines.append("    `excerpt` = VALUES(`excerpt`),")
        lines.append("    `content` = VALUES(`content`),")
        lines.append("    `status` = 'published',")
        lines.append("    `display_order` = VALUES(`display_order`),")
        lines.append("    `reading_time_minutes` = VALUES(`reading_time_minutes`),")
        lines.append("    `published_at` = COALESCE(`published_at`, NOW()),")
        lines.append("    `updated_at` = NOW();")
        lines.append("")

    lines.append("SET FOREIGN_KEY_CHECKS = 1;")
    lines.append("-- End of AptRun Go Programming Articles update")
    return "\n".join(lines)


def main():
    root_dir = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", "..", ".."))
    seeder_path = os.path.join(root_dir, "backend", "database", "seeders", "GoArticlesSeeder.php")
    sql_path = os.path.join(root_dir, "aws-go-articles-update-2026-11-23.sql")

    print(f"Total Go articles to process: {len(ALL_ARTICLES)}")

    php_code = generate_php_seeder(ALL_ARTICLES)
    with open(seeder_path, "w", encoding="utf-8") as f:
        f.write(php_code)
    print(f"Successfully generated {seeder_path} ({len(php_code)} bytes)")

    sql_code = generate_sql_file(ALL_ARTICLES)
    with open(sql_path, "w", encoding="utf-8") as f:
        f.write(sql_code)
    print(f"Successfully generated {sql_path} ({len(sql_code)} bytes)")

if __name__ == "__main__":
    main()
